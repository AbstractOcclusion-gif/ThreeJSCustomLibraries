function placements() {
  const random = seededRandom(7), out = [];
  const green = new THREE.Color(P.grass.color), muted = new THREE.Color(P.grass.soilColor), tint = new THREE.Color();
  const soilLayer = TERRAIN_LAYERS.indexOf('mud');
  for (let i = 0; i < P.grass.clumps; i++) {
    const a = random() * Math.PI * 2, r = Math.sqrt(random()) * P.grass.radius, x = Math.cos(a) * r, z = Math.sin(a) * r;
    const soil = field.layerWeightAt(x, z, soilLayer);
    const patch = THREE.MathUtils.smoothstep(meadowNoise(x / 4, z / 4), -.45, .45);
    const dry = Math.max(soil, patch);
    const brightness = 1 + (hash2(x, z, 3) - .5) * P.grass.tintVariation * .35;
    tint.lerpColors(green, muted, dry * P.grass.tintVariation).multiplyScalar(brightness);
    const yaw = random() * Math.PI * 2, individual = random();
    const densityPatch = THREE.MathUtils.smoothstep(meadowNoise(x / cover.patchSize, z / cover.patchSize), -.5, .5);
    if (hash2(x, z, 17) >= grassCoverageAt(field, x, z, cover, densityPatch)) continue;
    const heightMix = .65 * (1 - dry) + .35 * individual;
    const scale = P.grass.size * THREE.MathUtils.lerp(1, THREE.MathUtils.lerp(.28, 2.15, heightMix), P.grass.sizeVariation);
    out.push({x, z, y: heightAt(x, z) - .02, yaw, scale, tint: tint.toArray()});
  }
  return out;
}
function buildGrass() {
  grass?.dispose();
  const source = pack ?? free;
  const items = placements();
  grass = createGrassField({scene, geometries: source.grassGeometries, map: source.atlas, color: 0xffffff,
    placements: items, tileSize: 6, flatColorMix: .75, contactTracks: tracks});
  coverStats.clumps = items.length;
}
function plantSites(count, seed) {
  const random = seededRandom(seed);
  return Array.from({length: count}, () => {
    const angle = random() * Math.PI * 2, radius = 6 + random() * 34;
    return {x: Math.cos(angle) * radius, z: Math.sin(angle) * radius, yaw: random() * Math.PI * 2, size: random()};
  });
}
function placeTrees() {
  trees.place(plantSites(P.plants.trees, 11).map(({x, z, yaw, size}) => {
    const h = 6.5 * (.8 + size * .5);
    treeTint.lerpColors(shade, highlight, hash2(x, z, 7));
    return {x, z, yaw, h, r: h * .34 * P.plants.treeWidth, tint: treeTint.toArray()};
  }));
}
function shapeTrees() {
  trees.setProfile({
    ...trees.profile,
    crown: {...trees.profile.crown, depth: THREE.MathUtils.clamp(TREE_PROFILE.crown.depth * P.plants.treeCrown, .1, 1)},
    lobes: {...trees.profile.lobes, spread: 1 + (P.plants.asymmetry - .3) * .5},
  });
  treeProfileUI.sync();
}
function buildBushes() {
  bushes.place(plantSites(P.plants.bushes, 13).map(({x, z, yaw, size}) => {
    const h = 1.2 + size * .8;
    treeTint.lerpColors(shade, highlight, hash2(x, z, 7));
    return {x, z, yaw, h, r: h * .8, tint: treeTint.toArray()};
  }));
}
buildGrass(); placeTrees(); buildBushes();

const balls = createRollingBodies({scene, field, onContact(from, to, shape) {
  const bladeHeight = .35 * P.grass.size;
  const height = shape instanceof Sphere ? Math.min(shape.radius, bladeHeight) : 0;
  const footprint = height ? Math.sqrt(height * (2 * shape.radius - height)) : Math.max(.2, bladeHeight);
  grass.addSweep({fromX: from.x, fromZ: from.z, toX: to.x, toZ: to.z, radius: footprint});
}});
function launchBalls(count, box = false) {
  balls.setTrunks(trees);
  const target = trees.items.reduce((nearest, item) =>
    !nearest || Math.hypot(item.x, item.z) < Math.hypot(nearest.x, nearest.z) ? item : nearest, null);
  for (let i = 0; i < count; i++) {
    const radius = P.interact.ballRadius;
    const lane = i === 0 ? 0 : (i % 2 ? 1 : -1) * Math.ceil(i / 2);
    balls.launch({x: (target?.x ?? 0) + 7, z: (target?.z ?? 2) + lane * (2 * radius + .3),
      radius, speed: P.interact.ballSpeed, box});
  }
}
