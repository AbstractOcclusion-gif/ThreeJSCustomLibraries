const $ = id => document.getElementById(id);
const renderer = benchRenderer(); renderer.shadowMap.enabled = true; renderer.shadowMap.type = THREE.PCFSoftShadowMap;
const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera(50, innerWidth / innerHeight, .1, 400);
camera.position.set(13, 5.5, 16);
const controls = new OrbitControls(camera, renderer.domElement); controls.target.set(0, 1, 0); controls.enableDamping = true; controls.maxPolarAngle = Math.PI * .49; controls.update();
// Standalone: the basic stage gives sky, sun, wind and a flat ground; grass, trees and bushes read its environment.
const STAGE_SIZE = 128, START_WIND = 6;   // m: ground side; m/s: enough wind to see the plants move
const stage = createBasicStage({scene, shadows: true, groundSize: STAGE_SIZE, shadowMapSize: 2048, shadowExtent: 40});
const heightAt = () => 0;   // flat stage ground

// Assets: generated by default, Synty pack when present.
const syntyBase = await detectAssets(import.meta.env.BASE_URL + 'synty/vegetation/specimen-atlas.png', import.meta.env.BASE_URL + 'synty/vegetation/');
const free = createFreeVegetation({meadowBlades: true});
let pack = null; if (syntyBase) { try { pack = await loadSyntyVegetation({baseUrl: syntyBase}); } catch (e) { console.error(e); } }

const P = {
  grass: {clumps: 14000, radius: 45, size: 1, sizeVariation: .9, color: '#50762e', soilColor: '#c2aa61', tintVariation: .9, density: 1, lodDistance: 26, farDensity: .45, shadowDistance: 18, transmission: 1.45},
  plants: {trees: 14, bushes: 24, gust: .4, treeWidth: 1, treeCrown: 1, asymmetry: .3},
  interact: {ballSpeed: 6, ballRadius: 1.1, recoverySeconds: 3},
};
let grass;
const lighting = stage.lighting;
const trees = new LeavedTrees({scene, lighting, sampleGround: heightAt, leafTexture: free.atlas, leafRect: free.atlasRects.leaf});
const bushes = new LeavedTrees({scene, profile: 'bush', lighting, sampleGround: heightAt, leafTexture: free.atlas, leafRect: free.atlasRects.leaf});
const treeTint = new THREE.Color();
const shade = new THREE.Color('#2f6b1f'), highlight = new THREE.Color('#779640');
const comparison = [
  {profile: 'oak', x: -10, h: 5, r: 2.1},
  {profile: 'birch', x: 0, h: 6, r: 1.35},
  {profile: 'hawthorn', x: 10, h: 2.4, r: 1.5},
];
const variantRows = [4, 0, -4];
const specimens = comparison.map(({profile, x, h, r}) => {
  const plants = new LeavedTrees({scene, profile, lighting, sampleGround: heightAt, leafTexture: free.atlas, leafRect: free.atlasRects.leaf});
  plants.place(variantRows.map((z, variant) => ({x, z, h, r, variant, yaw: 0, tint: highlight.toArray()})));
  plants.setEnvironment(stage.environment);
  return plants;
});
const view = {layout: 'Species comparison'};
const meadowNoise = valueNoise(23);
function placements() {
  const random = seededRandom(7), out = [];
  const green = new THREE.Color(P.grass.color), muted = new THREE.Color(P.grass.soilColor), tint = new THREE.Color();
  for (let i = 0; i < P.grass.clumps; i++) {
    const a = random() * Math.PI * 2, r = Math.sqrt(random()) * P.grass.radius, x = Math.cos(a) * r, z = Math.sin(a) * r;
    const patch = THREE.MathUtils.smoothstep(meadowNoise(x / 4, z / 4), -.45, .45);
    const dry = patch;
    const brightness = 1 + (hash2(x, z, 3) - .5) * P.grass.tintVariation * .35;
    tint.lerpColors(green, muted, dry * P.grass.tintVariation).multiplyScalar(brightness);
    const yaw = random() * Math.PI * 2, individual = random();
    const heightMix = .65 * (1 - dry) + .35 * individual;
    const scale = P.grass.size * THREE.MathUtils.lerp(1, THREE.MathUtils.lerp(.28, 2.15, heightMix), P.grass.sizeVariation);
    out.push({x, z, y: heightAt(x, z) - .02, yaw, scale, tint: tint.toArray()});
  }
  return out;
}
function buildGrass() {
  grass?.dispose();
  const source = pack ?? free;
  const items = placements();
  grass = createGrassField({scene, geometries: source.grassGeometries, map: source.atlas, color: 0xffffff,
    placements: items, tileSize: 6, flatColorMix: .75});
}
function plantSites(count, seed) {
  const random = seededRandom(seed);
  return Array.from({length: count}, () => {
    const angle = random() * Math.PI * 2, radius = 6 + random() * 34;
    return {x: Math.cos(angle) * radius, z: Math.sin(angle) * radius, yaw: random() * Math.PI * 2, size: random()};
  });
}
function placeTrees() {
  trees.place(plantSites(P.plants.trees, 11).map(({x, z, yaw, size}) => {
    const h = 6.5 * (.8 + size * .5);
    treeTint.lerpColors(shade, highlight, hash2(x, z, 7));
    return {x, z, yaw, h, r: h * .34 * P.plants.treeWidth, tint: treeTint.toArray()};
  }));
}
function shapeTrees() {
  trees.setProfile({
    ...trees.profile,
    crown: {...trees.profile.crown, depth: THREE.MathUtils.clamp(TREE_PROFILE.crown.depth * P.plants.treeCrown, .1, 1)},
    lobes: {...trees.profile.lobes, spread: 1 + (P.plants.asymmetry - .3) * .5},
  });
  treeProfileUI.sync();
}
function buildBushes() {
  bushes.place(plantSites(P.plants.bushes, 13).map(({x, z, yaw, size}) => {
    const h = 1.2 + size * .8;
    treeTint.lerpColors(shade, highlight, hash2(x, z, 7));
    return {x, z, yaw, h, r: h * .8, tint: treeTint.toArray()};
  }));
}
buildGrass(); placeTrees(); buildBushes();

// Grass flattening under a rolling ball: blades are bladeShare x clump size tall; a box sweeps at least minFootprint m wide.
const CONTACT = Object.freeze({bladeShare: .35, minFootprint: .2});
const BALL_LAUNCH = Object.freeze({ahead: 7, gap: .3, stress: 8});   // m before the nearest tree; m between lanes; balls
const balls = createRollingBodies({scene, onContact(from, to, shape) {
  const bladeHeight = CONTACT.bladeShare * P.grass.size;
  const height = shape instanceof Sphere ? Math.min(shape.radius, bladeHeight) : 0;
  const footprint = height ? Math.sqrt(height * (2 * shape.radius - height)) : Math.max(CONTACT.minFootprint, bladeHeight);
  grass.addSweep({fromX: from.x, fromZ: from.z, toX: to.x, toZ: to.z, radius: footprint});
}});
function launchBalls(count, box = false) {
  if (view.layout !== 'Meadow') {
    view.layout = 'Meadow';
    applyView();
    viewControl.updateDisplay();
  }
  balls.setTrunks(trees);
  const target = trees.items.reduce((nearest, item) =>
    !nearest || Math.hypot(item.x, item.z) < Math.hypot(nearest.x, nearest.z) ? item : nearest, null);
  for (let i = 0; i < count; i++) {
    const radius = P.interact.ballRadius;
    const lane = i === 0 ? 0 : (i % 2 ? 1 : -1) * Math.ceil(i / 2);
    balls.launch({x: (target?.x ?? 0) + BALL_LAUNCH.ahead, z: (target?.z ?? 2) + lane * (2 * radius + BALL_LAUNCH.gap),
      radius, speed: P.interact.ballSpeed, box});
  }
}
const rollBall = () => launchBalls(1);

const gui = createBenchPanel('Vegetation');
function applyView() {
  const compare = view.layout === 'Species comparison';
  trees.group.visible = bushes.group.visible = !compare;
  for (const plants of specimens) plants.group.visible = compare;
  $('species-order').hidden = !compare;
  camera.position.set(...(compare ? [0, 10, 30] : [13, 5.5, 16]));
  controls.target.set(0, compare ? 2.6 : 1, 0);
  controls.update();
}
const viewControl = gui.add(view, 'layout', ['Species comparison', 'Meadow']).name('View').onChange(applyView);
applyView();
const stageUI = stageControls(gui, stage);
Object.assign(stageUI.state, {windSpeed: START_WIND, gust: P.plants.gust}); stageUI.apply();
stageUI.folder.controllersRecursive().forEach(c => c.updateDisplay());
stageUI.folder.controllers.find(c => c.property === 'gust').hide();   // Plants > gust drives it (saved in the presets)
grassControls(gui, {settings: P.grass, rebuild: buildGrass});
plantControls(gui, {plants: P.plants, interact: P.interact, placeTrees, buildBushes, shapeTrees, rollBall,
  stress: () => launchBalls(BALL_LAUNCH.stress), slide: () => launchBalls(1, true)});
const treeProfileUI = treeProfileControls(gui, {title: 'Tree profile', trees, onChange(profile) {
  P.plants.treeCrown = profile.crown.depth / TREE_PROFILE.crown.depth;
  P.plants.asymmetry = .3 + (profile.lobes.spread - 1) * 2;
  gui.controllersRecursive().forEach(control => control.updateDisplay());
}});
treeProfileControls(gui, {title: 'Bush profile', trees: bushes});
presetsFolder(gui, {bundled: import.meta.glob('../../presets/vegetation/*.json'), name: 'vegetation',
  getState: () => ({schema: 'three-kit.vegetation', version: 1, grass: {...P.grass}, plants: {...P.plants}}),
  apply: p => {
    Object.assign(P.grass, p.grass); Object.assign(P.plants, p.plants);
    buildGrass(); trees.place([]); shapeTrees(); placeTrees(); buildBushes();
    gui.controllersRecursive().forEach(c => c.updateDisplay());
  }});

const unbindResize = bindResize(renderer, camera);
let lastUI = 0;
startFrameLoop(renderer, (dt, now) => {
  controls.update(); stage.update(camera);
  const environment = stage.environment; environment.wind.gust = P.plants.gust;
  trees.setEnvironment(environment); bushes.setEnvironment(environment);
  trees.update(dt); bushes.update(dt);
  for (const plants of specimens) if (plants.group.visible) plants.update(dt);
  balls.update(dt);
  grass.update(dt, {camera, environment, transmission: P.grass.transmission * environment.daylight, lodDistance: P.grass.lodDistance, farDensity: P.grass.farDensity, shadowDistance: P.grass.shadowDistance, density: P.grass.density, recoverySeconds: P.interact.recoverySeconds});
  renderer.render(scene, camera);
  if (now - lastUI > STATUS_REFRESH_MS) { lastUI = now; const s = grass.stats; $('status').textContent = (pack ? 'Synty pack: private-assets' : 'Generated atlas & clumps') + `\n${s.visibleClumps.toLocaleString()} clumps in view · ${s.visibleTiles} tiles · ${s.shadowTiles} shadow tiles · ${s.activeSweeps} sweeps\nwind ${stageUI.state.windSpeed.toFixed(1)} m/s`; }
});
document.body.dataset.ready = 'true';
onLeave(() => {
  renderer.setAnimationLoop(null); unbindResize();
  grass?.dispose(); trees.dispose(); bushes.dispose(); free.grassGeometries.forEach(geometry => geometry.dispose()); free.dispose();
  for (const plants of specimens) plants.dispose();
  stage.dispose(); controls.dispose(); gui.destroy(); renderer.dispose();
});
window.vegetationBench = {get grass() { return grass; }, trees, bushes, rollBall, bodies: balls, stage, scene, camera, renderer, pack};
